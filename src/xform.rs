//! Mem-TileTransform (TODO 102): a memory test under the matrix unit's load. Designed and timed in plumb (`bench/src/xform.rs`, design
//! `../fearlessD/design/amx-transform-verify.md`); here on TMR's own tile layer (`amx`) and its harness (Tier 2, the seal, `Rescan`).
//!
//! Each chunk goes through three phases, each one walk over it:
//! - **W** stores a pattern tile (1 KiB) into each tile of the chunk. A group is `X` consecutive tiles and holds each of the set's `X`
//!   patterns once, in a rotation that changes every pass (`rotation`). Groups are counted from the extent's start, so a tile's pattern
//!   depends on where it is, not on which chunk wrote it: chunks start on 4 KiB, may overlap, and leave the same image at any chunk size.
//! - **RW** loads each tile, multiplies it by the set's transform matrix `K` (`TDPBUUD`) and stores the 16x16 u32 result in place, so
//!   memory holds `T(P) = P x K`, which differs bit for bit from the pattern.
//! - **R** loads each tile once and adds its product with its pattern's own matrix into the group's running checksum `1 + r` times (`r`,
//!   `tile_load`, is the CPU-load setting, up to 65534), then compares it with the constant every clean group gives. Every multiply's
//!   result is in the checksum, so a matrix unit that miscomputes under load shows as a mismatch too. A chunk's partial groups at its
//!   ends are compared word by word instead.
//!
//! A mismatch is rescanned at once through TMR's `Rescan` (the bad words, their rereads, "not reproduced"), with a line per bad tile
//! saying what its differences look like (one stored bit, or one bit of the pattern flipped before the transform, named by pattern byte
//! and bit), and a group's checksum is then recomputed through the tiles, the other load path.
//!
//! Guarantees (`Matrices::generate`): any one or two flipped bits in a group's stored result change the checksum, at any `r`. Flips in
//! the pattern before the transform are caught for the built-in set exhaustively (a test), three or more with overwhelming odds.
//!
//! The expected values are computed on the tiles, by these kernels. The built-in set's group checksum is also stored in the binary
//! (`xform_builtin.rs`, generated by the tests' scalar reference), and `self_test` compares the two before the test relies on the matrix
//! unit: a mismatch is a CPU fault, reported as one error, before any memory is tested.
//!
//! The kernels are `#[target_feature(enable = "amx-tile,amx-int8")]` functions, each configuring the tiles for its own call (`amx::
//! configure`); the stdarch intrinsics name the tile registers by number. Those intrinsics are opaque to LLVM (it treats each as reading
//! and writing any memory), so a kernel takes everything it uses as values, in registers: what sits behind a reference would be reloaded
//! after every tile operation.

