/// The test's name, as it is registered.
pub(crate) const TEST_NAME: &str = "Mem-TileTransform";

/// u64 words a tile (1 KiB).
pub(crate) const TILE_U64: usize = TILE_BYTES / 8;

/// The row stride of every tile load and store: a tile is 16 consecutive lines.
const STRIDE: usize = ROW_BYTES;

/// Patterns a set has when `tile_patterns` is unset: the built-in set's.
pub(crate) const DEFAULT_X: u32 = 16;

/// The most extra multiplies a tile (`tile_load`): `1 + r` times any one- or two-bit fault's change to the checksum, which is below 2^16,
/// stays below 2^32, so it can't wrap to zero.
pub(crate) const MAX_R: u32 = 65534;

/// The built-in set's seed: its patterns and matrices, whose group checksum `xform_builtin.rs` stores. Every `X` takes its set from it,
/// so a run's patterns are the ones the tests checked; the run's seed sets the rotation. "TMR_XFM1".
const BUILTIN_SEED: u64 = 0x544D_525F_5846_4D31;

include!("xform_builtin.rs");

/// From this load setting up, R reads ahead (`group_sums_ahead`); below it, a pair at a time (`group_sums_pairs`). Measured in plumb
/// (2026-10-23, `bench/RESULTS.md`): reading ahead wins 6-10% in DRAM from r = 6, ties at 5, and loses 4-13% from 0 to 4, where each
/// tile's few multiplies leave the earlier loads nothing to overlap with.
const AHEAD_FROM_R: usize = 6;

/// Multiplies a call of the R kernel does at most, about 10 ms: a high `tile_load` makes a group cost up to `X * 65535` multiplies, so R
/// runs in batches of groups, with the shutdown check between them.
const BATCH_MULTIPLIES: usize = 1 << 20;

/// `verify_groups`' answer when every group matched.
const NONE: usize = usize::MAX;

/// One tile's worth of data: a pattern, or memory holding `T(P)`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[repr(C, align(64))]
pub(crate) struct Tile(pub(crate) [u64; TILE_U64]);

/// A VNNI-packed 64x16 byte matrix (one tile): logical `[j][n]` (column `j` < 64, output column `n` < 16) sits at tile row `j / 4`, byte
/// `4n + j % 4` of that row, the packing TDPBUUD's B operand takes.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[repr(C, align(64))]
pub(crate) struct Matrix(pub(crate) [u64; TILE_U64]);

impl Matrix {
    /// Logical entry `[j][n]`, `j` < 64, `n` < 16.
    pub(crate) fn get(&self, j: usize, n: usize) -> u8 {
        let byte = (j / 4) * ROW_BYTES + 4 * n + j % 4;
        (self.0[byte / 8] >> (byte % 8 * 8)) as u8
    }

    /// Logical row `j`, `[j][0..16]`: what byte `j` of a data row is multiplied by, one entry an output column.
    pub(crate) fn row(&self, j: usize) -> [u8; 16] {
        std::array::from_fn(|n| self.get(j, n))
    }
}

/// A seeded xorshift64 stream for the set's patterns and matrices: not part of what is tested, and kept as plumb's, so the built-in set
/// is plumb's too.
struct Rng(u64);

impl Rng {
    fn new(seed: u64) -> Rng {
        Rng(seed | 1)
    }

    fn next_u64(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x << 13;
        x ^= x >> 7;
        x ^= x << 17;
        self.0 = x;
        x
    }
}

/// A set's patterns and matrices, from its seed alone: what the guarantees rest on, and what the scalar reference checks.
pub(crate) struct Matrices<const X: usize> {
    pub(crate) patterns: Box<[Tile; X]>,
    pub(crate) transform: Matrix,
    /// The checksum matrix of each pattern.
    pub(crate) keys: Box<[Matrix; X]>,
}

impl<const X: usize> Matrices<X> {
    /// The set from `seed`: `X` patterns (16, 32 or 64), the transform matrix, a checksum matrix a pattern.
    ///
    /// Every matrix byte is odd, and the logical matrix rows (`Matrix::row`) are distinct across the set's `X` matrices. That gives two
    /// guarantees:
    /// - **Any single flipped bit in a group's stored result** changes byte `j` of data row `m` by `d = +-2^b`, and so the checksum's row
    ///   `m` by `d * K[j][n]` in each of its 16 entries. With `K` odd, `|d * K| < 2^15` is never 0 mod 2^32.
    /// - **Any two.** Changes in different rows can't cancel. In one row, `d1 * K1[j1][n]` and `d2 * K2[j2][n]` cancel for all 16 `n` only
    ///   if they're equal and opposite: since both matrices are odd, `|d1| = |d2|` (the same bit, flipped in opposite directions) and the
    ///   rows `K1[j1]` and `K2[j2]` are equal, which the construction rules out.
    ///
    /// Each product goes into the checksum `1 + r` times, so a fault changes it by `1 + r` times its change at `r` = 0: below 2^16 in both
    /// cases above, times at most 65535 (`MAX_R`), stays below 2^32 and nonzero. The transform's 64 rows are distinct too, so a bit
    /// flipped before the transform leaves a row delta that names its byte (`Signature::BeforeTransform`).
    pub(crate) fn generate(seed: u64) -> Self {
        const { assert!(X == 16 || X == 32 || X == 64, "X must be 16, 32 or 64") };
        let mut rng = Rng::new(seed);
        let patterns = gen_patterns::<X>(&mut rng);
        let transform = distinct_odd_matrices(1, &mut rng)[0];
        let keys = distinct_odd_matrices(X, &mut rng).try_into().expect("X matrices");
        Matrices { patterns, transform, keys }
    }
}

/// `count` matrices with every byte odd and every logical row distinct, within each matrix and across them. Rows are 16 odd bytes (a
/// 2^112 space), so a repeat is astronomically unlikely; a matrix with one is drawn again.
fn distinct_odd_matrices(count: usize, rng: &mut Rng) -> Vec<Matrix> {
    let mut seen = HashSet::new();
    let mut out = Vec::with_capacity(count);
    while out.len() < count {
        let m = Matrix(std::array::from_fn(|_| rng.next_u64() | 0x0101_0101_0101_0101));
        let rows: HashSet<[u8; 16]> = (0..64).map(|j| m.row(j)).collect();
        if rows.len() == 64 && rows.is_disjoint(&seen) {
            seen.extend(rows);
            out.push(m);
        }
    }
    out
}

/// The set's `X` pattern tiles: the classic memory-test patterns (solid zeros and ones, the two checkerboards, walking ones and walking
/// zeros along each word), then seeded pseudo-random tiles.
fn gen_patterns<const X: usize>(rng: &mut Rng) -> Box<[Tile; X]> {
    let walk = |w: usize| 1u64 << (w % 64);
    let classic = [
        Tile([0; TILE_U64]),
        Tile([!0; TILE_U64]),
        Tile([0xAAAA_AAAA_AAAA_AAAA; TILE_U64]),
        Tile([0x5555_5555_5555_5555; TILE_U64]),
        Tile(std::array::from_fn(walk)),
        Tile(std::array::from_fn(|w| !walk(w))),
    ];
    let random = std::iter::repeat_with(|| Tile(std::array::from_fn(|_| rng.next_u64())));
    let all: Vec<Tile> = classic.into_iter().chain(random).take(X).collect();
    all.try_into().expect("X tiles")
}

/// MurmurHash3's 64-bit finalizer, as plumb's: a cheap, well-mixed hash, used to key the rotation.
fn hash64(mut x: u64) -> u64 {
    x ^= x >> 33;
    x = x.wrapping_mul(0xff51_afd7_ed55_8ccd);
    x ^= x >> 33;
    x = x.wrapping_mul(0xc4ce_b9fe_1a85_ec53);
    x ^= x >> 33;
    x
}

/// The rotation offset of group `g` (counted from the extent's start) on pass `pass`: tile `t` of the extent holds pattern
/// `(t + offset) % X`.
///
/// Over each cycle of `X` passes the offsets are a permutation of `0..X`, so every tile holds every pattern once a cycle. The permutation
/// is an affine step, an xorshift and another affine step, each a bijection mod `X` (odd multipliers), keyed by a hash of the layout, the
/// group and the cycle. Its `X^4 / 4` keys give as many distinct permutations (counted at X = 16 and 32), so two groups hold the same data
/// on a given pass 1 time in `X`, and on every pass of a cycle (hiding an addressing fault between them for that cycle) 1 time in
/// `X^4 / 4`, a different pair each cycle.
#[inline(always)]
fn rotation<const X: usize>(layout: u64, g: usize, pass: usize) -> usize {
    let m = X - 1;
    let k = hash64(hash64(layout ^ g as u64).wrapping_add((pass / X) as u64)) as usize;
    let v = (pass & m).wrapping_mul(k | 1).wrapping_add(k >> 8) & m;
    let v = v ^ (v >> (X.trailing_zeros() / 2));
    v.wrapping_mul((k >> 16) | 1).wrapping_add(k >> 24) & m
}

/// The set a test call runs with: its matrices, the load setting, the rotation's layout, and every expected value, computed on the tiles.
pub(crate) struct PatternSet<const X: usize> {
    m: Matrices<X>,
    r: usize,
    layout: u64,
    /// `T(P_i)` for each pattern.
    expected_t: Box<[Tile; X]>,
    /// The group checksum at r = 0, `E = sum_i T(P_i) x K_i`: the same for every group and pass, since a group holds every pattern once and
    /// multiplies each by its own matrix, whatever the rotation.
    checksum: Tile,
    /// The group checksum R compares with, at this set's `r`: `(1 + r) E`.
    expected_sum: Tile,
}

impl<const X: usize> PatternSet<X> {
    /// The set of `m`, with `r` extra multiplies a tile in R and the rotation's `layout`: `T(P_i)` through RW's kernel, then the checksums of
    /// a group holding them in order (rotation 0) through R's, at r = 0 and at `r`.
    ///
    /// # Safety
    /// The CPU has AMX-INT8 (`amx::has_amx_int8`).
    pub(crate) unsafe fn new(m: Matrices<X>, r: usize, layout: u64) -> Self {
        let mut t: Vec<Tile> = m.patterns.to_vec();
        // SAFETY: AMX-INT8 (the caller's); `t` is X tiles
        unsafe { transform_tiles(t.as_mut_ptr().cast(), X, &raw const m.transform) };
        let expected_t: Box<[Tile; X]> = t.try_into().expect("X tiles");
        let group = expected_t.as_ptr().cast::<u64>();
        let keys = m.keys.as_ptr();
        // SAFETY: as above; `group` is X tiles and `keys` X matrices
        let (checksum, expected_sum) = unsafe { (group_checksum::<X>(group, keys, 0), group_checksum::<X>(group, keys, r)) };
        PatternSet { m, r, layout, expected_t, checksum, expected_sum }
    }

    /// The pattern at tile `t` of the extent on pass `pass`.
    fn pattern_at(&self, t: usize, pass: usize) -> usize {
        (t + rotation::<X>(self.layout, t / X, pass)) & (X - 1)
    }

    /// What R takes of the set, as values (see the module doc).
    fn check(&self) -> Check {
        Check { keys: self.m.keys.as_ptr(), expected: &raw const self.expected_sum, layout: self.layout, r: self.r }
    }
}

/// The matrix unit before the test relies on it: the built-in set, recomputed on the tiles, against its stored checksum. Comparing the
/// checksum covers every `T(P_i)` too: it sums them all, each times its own matrix, so a wrong `T(P_i)` shows there with the guarantees of
/// `Matrices::generate`.
///
/// # Safety
/// The CPU has AMX-INT8 (`amx::has_amx_int8`).
pub(crate) unsafe fn self_test() -> bool {
    // SAFETY: the caller's
    unsafe { PatternSet::<16>::new(Matrices::generate(BUILTIN_SEED), 0, 0) }.checksum.0 == BUILTIN_CHECKSUM
}

