/// Under `errors=halt`, ends the test where it is once it has found errors (as `tests::halt_here!`).
macro_rules! halt_here {
    ($runner:expr, $cycle_errors:expr, $ops:expr) => {
        if $runner.should_halt($cycle_errors) {
            let total_operations = $ops;
            return $runner.finish_aborted($cycle_errors, total_operations);
        }
    };
}

/// Mem-TileTransform (TODO 102). The CPU has AMX-INT8 (`amx::has_amx_int8`): the run leaves out a test it can't run
/// (`runner::leave_out_what_the_cpu_lacks`).
#[doc = include_str!("test_fn_safety.md")]
pub unsafe fn tile_transform_multi(
    blocks: &[crate::runner::AllocationBlock], thread_id: usize, error_mode: crate::ErrorMode, timing: &TestTiming,
    config: &TestMemoryConfig, progress: Option<&TestProgress>,
) -> TestStats {
    let (runner, extent) = TestRunner::new(blocks, thread_id, error_mode, timing, config, progress, TEST_NAME, TestAction::ReadWrite);
    let context = config.parameter_context.as_ref();
    let r = context.and_then(|c| c.tile_load).unwrap_or(0) as usize;
    // SAFETY: the caller's (the blocks, AMX-INT8)
    unsafe {
        match context.and_then(|c| c.tile_patterns).unwrap_or(DEFAULT_X) {
            32 => run::<32>(runner, extent, thread_id, config, r),
            64 => run::<64>(runner, extent, thread_id, config, r),
            // 16; a config can give no other (`config::ModernConfig::build_test`)
            _ => run::<16>(runner, extent, thread_id, config, r),
        }
    }
}

/// The test at `X` patterns a set: the matrix unit's self-test, then per cycle and chunk W, RW and R, each chunk checked by the seal
/// before and resealed after.
unsafe fn run<const X: usize>(
    mut runner: TestRunner, extent: TestBlock<'_>, thread_id: usize, config: &TestMemoryConfig, r: usize,
) -> TestStats {
    if extent.test_size == 0 {
        return runner.finish_completed(0);
    }
    // SAFETY: AMX-INT8 (the caller's)
    if !unsafe { self_test() } {
        log::error!(
            "{}: the matrix unit computed the built-in pattern set's checksum wrongly: a fault in the CPU, before any memory was tested",
            crate::error_context::found_by(TEST_NAME)
        );
        return runner.finish_aborted(1, 0);
    }
    // The rotation's layout: the step's key (seed, suite cycle, step) and the thread, so threads and steps arrange their tiles apart
    let layout = crate::pattern::fmix(config.epoch.key() ^ crate::pattern::word_base(thread_id));
    // SAFETY: AMX-INT8
    let set = unsafe { PatternSet::<X>::new(Matrices::generate(BUILTIN_SEED), r, layout) };
    let check = set.check();
    let patterns = set.m.patterns.as_ptr();
    let transform = &raw const set.m.transform;
    let base = extent.ptr.cast::<u64>();
    let (flush, line_bytes) = (config.flush_before_verify, config.cache_line_bytes);
    let batch = (BATCH_MULTIPLIES / (X * (1 + r))).max(1);
    let ops = |runner: &TestRunner| (runner.bytes_processed() / std::mem::size_of::<u64>()) as u64;
    runner.restart_clock();

    loop {
        let cycle = runner.begin_cycle();
        let pass = cycle as usize - 1;
        let mut cycle_errors = 0u64;
        // Chunks of exactly the test's size, spread evenly over the extent (TODO 76): on 4 KiB, so a chunk's ends may cut a group
        let spread = runner.chunks(extent.test_size);
        for k in 0..spread.count() {
            let (start, len) = (spread.start(k), spread.chunk());
            runner.check_seal(start, len);
            halt_here!(runner, cycle_errors, ops(&runner));
            let (first, end) = (start / TILE_BYTES, (start + len) / TILE_BYTES);
            // SAFETY: tiles first..end are the chunk, inside the extent; AMX-INT8
            unsafe {
                write_tiles::<X>(base, first, end, patterns, layout, pass);
                transform_tiles(base.add(first * TILE_U64), end - first, transform);
                if flush {
                    crate::tests::flush_range_to_dram(base.add(first * TILE_U64).cast(), len, line_bytes);
                }
            }

            // R: the chunk's whole groups by their checksums, its partial groups at either end word by word
            let (g_from, g_to) = (first.div_ceil(X), end / X);
            let (head_end, tail_start) = if g_from < g_to { (g_from * X, g_to * X) } else { (end, end) };
            for (from, to) in [(first, head_end), (tail_start, end)] {
                // SAFETY: tiles of the chunk
                if from < to && unsafe { verify_part::<X>(base, from, to, &set, pass) } != 0 {
                    let what = format!("pass {pass}: tiles {from}..{to}, outside a whole group, compared word by word");
                    // SAFETY: as above
                    cycle_errors += unsafe { rescan_tiles::<X>(base, from, to, &set, pass, &what) };
                    halt_here!(runner, cycle_errors, ops(&runner));
                }
            }
            let mut g = g_from;
            while g < g_to {
                let stop = (g + batch).min(g_to);
                // SAFETY: groups of the chunk; AMX-INT8
                let bad = unsafe { verify_groups::<X>(base, g, stop, check, pass) };
                if bad == NONE {
                    g = stop;
                } else {
                    // SAFETY: as above
                    cycle_errors += unsafe { rescan_group::<X>(base, bad, &set, pass) };
                    halt_here!(runner, cycle_errors, ops(&runner));
                    g = bad + 1;
                }
                if runner.shutdown_requested() {
                    return runner.finish_aborted(cycle_errors, ops(&runner));
                }
            }

            // Count the chunk when it is done (W 1, RW 2, R 1 bytes a byte); overlaps count each time
            runner.add_bytes(len * 4);
            halt_here!(runner, cycle_errors, ops(&runner));
            runner.reseal(start, len);
            if runner.should_halt(cycle_errors) || runner.shutdown_requested() {
                return runner.finish_aborted(cycle_errors, ops(&runner));
            }
        }

        runner.commit_cycle_errors(cycle_errors);
        runner.update_progress();
        if !runner.should_continue() {
            return runner.finish_completed(ops(&runner));
        }
    }
}

