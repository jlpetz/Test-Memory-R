/// **W** on tiles `first..end` of the extent at `base`: each tile its pattern. A chunk's partial groups at its ends go a tile at a time,
/// both before the whole groups, so the whole groups' loop holds only its own values (with the tail after it, `base` and `end` stayed live
/// through it and two values a group came from the stack); its whole groups a pair at a time (tiles 0 and 1), their patterns at fixed
/// offsets once the group's rotation is known.
///
/// # Safety
/// AMX-INT8; `base` the extent's start, `first..end` tiles inside it; `patterns` the set's `X` tiles.
#[inline(never)]
#[target_feature(enable = "amx-tile,amx-int8")]
unsafe fn write_tiles<const X: usize>(base: *mut u64, first: usize, end: usize, patterns: *const Tile, layout: u64, pass: usize) {
    let _tiles = crate::amx::configure();
    let head = first.next_multiple_of(X).min(end);
    let whole_end = (end / X * X).max(head);
    write_part::<X>(base, first, head, patterns, layout, pass);
    write_part::<X>(base, whole_end, end, patterns, layout, pass);
    let mut p = base.add(head * TILE_U64);
    let stop = base.wrapping_add(whole_end * TILE_U64);
    let mut g = head / X;
    while p < stop {
        // One value (`opaque_u64`, Rule 6.14): seen through, the sum's two terms were kept apart and re-added at each tile
        let off = crate::tests::opaque_u64(rotation::<X>(layout, g, pass) as u64) as usize;
        let mut i = 0;
        while i < X {
            _tile_loadd::<0>(patterns.add((i + off) & (X - 1)).cast(), STRIDE);
            _tile_loadd::<1>(patterns.add((i + 1 + off) & (X - 1)).cast(), STRIDE);
            _tile_stored::<0>(p.add(i * TILE_U64).cast(), STRIDE);
            _tile_stored::<1>(p.add((i + 1) * TILE_U64).cast(), STRIDE);
            i += 2;
        }
        p = p.wrapping_add(X * TILE_U64);
        g += 1;
    }
}

/// W a tile at a time, for tiles `from..to` of one partial group (inside `write_tiles`' tile session): the group's rotation once.
#[inline(always)]
unsafe fn write_part<const X: usize>(base: *mut u64, from: usize, to: usize, patterns: *const Tile, layout: u64, pass: usize) {
    if from >= to {
        return;
    }
    debug_assert_eq!(from / X, (to - 1) / X, "one group");
    let off = rotation::<X>(layout, from / X, pass);
    for t in from..to {
        let pattern = (t + off) & (X - 1);
        _tile_loadd::<0>(patterns.add(pattern).cast(), STRIDE);
        _tile_stored::<0>(base.add(t * TILE_U64).cast(), STRIDE);
    }
}

/// **RW** on `count` tiles from `tiles`: each multiplied in place by the transform matrix, which stays in tile 7 for the call. Tiles go
/// four at a time, read ahead: each pair's loads (into tiles 4, 5 or 2, 3) are issued before the pair ahead of it is multiplied (into 0,
/// 1) and stored, so four tiles are in flight from DRAM, not two (5-7% in DRAM in plumb). The tail goes a tile at a time.
///
/// # Safety
/// AMX-INT8; `tiles..tiles + count` tiles of memory; `k` a matrix.
#[inline(never)]
#[target_feature(enable = "amx-tile,amx-int8")]
unsafe fn transform_tiles(tiles: *mut u64, count: usize, k: *const Matrix) {
    let _tiles = crate::amx::configure();
    _tile_loadd::<7>(k.cast(), STRIDE);
    let stop = tiles.wrapping_add(count / 4 * 4 * TILE_U64);
    let mut p = tiles;
    if p < stop {
        _tile_loadd::<4>(p.cast(), STRIDE);
        _tile_loadd::<5>(p.add(TILE_U64).cast(), STRIDE);
    }
    while p < stop {
        let next = p.wrapping_add(4 * TILE_U64);
        _tile_loadd::<2>(p.add(2 * TILE_U64).cast(), STRIDE);
        _tile_loadd::<3>(p.add(3 * TILE_U64).cast(), STRIDE);
        _tile_zero::<0>();
        _tile_zero::<1>();
        _tile_dpbuud::<0, 4, 7>();
        _tile_dpbuud::<1, 5, 7>();
        _tile_stored::<0>(p.cast(), STRIDE);
        _tile_stored::<1>(p.add(TILE_U64).cast(), STRIDE);
        if next < stop {
            _tile_loadd::<4>(next.cast(), STRIDE);
            _tile_loadd::<5>(next.add(TILE_U64).cast(), STRIDE);
        }
        _tile_zero::<0>();
        _tile_zero::<1>();
        _tile_dpbuud::<0, 2, 7>();
        _tile_dpbuud::<1, 3, 7>();
        _tile_stored::<0>(p.add(2 * TILE_U64).cast(), STRIDE);
        _tile_stored::<1>(p.add(3 * TILE_U64).cast(), STRIDE);
        p = next;
    }
    let end = tiles.wrapping_add(count * TILE_U64);
    while p < end {
        _tile_loadd::<4>(p.cast(), STRIDE);
        _tile_zero::<0>();
        _tile_dpbuud::<0, 4, 7>();
        _tile_stored::<0>(p.cast(), STRIDE);
        p = p.wrapping_add(TILE_U64);
    }
}

/// What R takes of the set, as values in registers.
#[derive(Clone, Copy)]
struct Check {
    keys: *const Matrix,
    expected: *const Tile,
    layout: u64,
    r: usize,
}

/// **R** on whole groups `from..to` of the extent at `base` (counted from its start): each group's checksum against the expected one.
/// Returns the first group that disagrees, or `NONE`.
///
/// # Safety
/// AMX-INT8; groups `from..to` inside the extent; `check` the set's.
#[inline(never)]
#[target_feature(enable = "amx-tile,amx-int8")]
unsafe fn verify_groups<const X: usize>(base: *const u64, from: usize, to: usize, check: Check, pass: usize) -> usize {
    let Check { keys, expected, layout, r } = check;
    let _tiles = crate::amx::configure();
    // The two chains' sums, as the tiles store them: written whole before they are read
    let mut sums = std::mem::MaybeUninit::<[u32; 4 * TILE_U64]>::uninit();
    let sums = sums.as_mut_ptr().cast::<u32>();
    let mut p = base.add(from * X * TILE_U64);
    for g in from..to {
        group_sums::<X>(p, keys, rotation::<X>(layout, g, pass), r, sums);
        if !sums_match(sums, expected) {
            return g;
        }
        p = p.wrapping_add(X * TILE_U64);
    }
    NONE
}

/// R's loop: `group`'s checksum, as two chains (tiles 0 and 1) that `sums` gets and `sums_match` adds up. Each tile of a pair has its own
/// matrix (tiles 5, 7) and chain, so the two chains of multiplies don't wait on each other; each tile's product goes into its chain
/// `1 + r` times (`AHEAD_FROM_R` picks the loop). Inside a kernel's tile session.
#[inline(always)]
unsafe fn group_sums<const X: usize>(group: *const u64, keys: *const Matrix, off: usize, r: usize, sums: *mut u32) {
    _tile_zero::<0>();
    _tile_zero::<1>();
    if r >= AHEAD_FROM_R {
        group_sums_ahead::<X>(group, keys, off, r);
    } else {
        group_sums_pairs::<X>(group, keys, off, r);
    }
    _tile_stored::<0>(sums.cast(), STRIDE);
    _tile_stored::<1>(sums.add(2 * TILE_U64).cast(), STRIDE);
}

/// The pattern matrix of tile `i` of a group whose rotation is `off`.
#[inline(always)]
unsafe fn key<const X: usize>(keys: *const Matrix, i: usize, off: usize) -> *const u8 {
    keys.add((i + off) & (X - 1)).cast()
}

/// A pair at a time: its data (tiles 4, 6) and matrices (5, 7), then its multiplies.
#[inline(always)]
unsafe fn group_sums_pairs<const X: usize>(group: *const u64, keys: *const Matrix, off: usize, r: usize) {
    let mut i = 0;
    while i < X {
        _tile_loadd::<4>(group.add(i * TILE_U64).cast(), STRIDE);
        _tile_loadd::<5>(key::<X>(keys, i, off), STRIDE);
        _tile_loadd::<6>(group.add((i + 1) * TILE_U64).cast(), STRIDE);
        _tile_loadd::<7>(key::<X>(keys, i + 1, off), STRIDE);
        pair_sums::<4, 6>(r);
        i += 2;
    }
}

/// Four tiles at a time, read ahead: each pair's loads (into tiles 4, 6 or 2, 3) are issued before the pair ahead of it is multiplied, so
/// four tiles are in flight from DRAM, not two.
#[inline(always)]
unsafe fn group_sums_ahead<const X: usize>(group: *const u64, keys: *const Matrix, off: usize, r: usize) {
    _tile_loadd::<4>(group.cast(), STRIDE);
    _tile_loadd::<6>(group.add(TILE_U64).cast(), STRIDE);
    let mut q = 0;
    while q < X {
        _tile_loadd::<2>(group.add((q + 2) * TILE_U64).cast(), STRIDE);
        _tile_loadd::<3>(group.add((q + 3) * TILE_U64).cast(), STRIDE);
        _tile_loadd::<5>(key::<X>(keys, q, off), STRIDE);
        _tile_loadd::<7>(key::<X>(keys, q + 1, off), STRIDE);
        pair_sums::<4, 6>(r);
        if q + 4 < X {
            _tile_loadd::<4>(group.add((q + 4) * TILE_U64).cast(), STRIDE);
            _tile_loadd::<6>(group.add((q + 5) * TILE_U64).cast(), STRIDE);
        }
        _tile_loadd::<5>(key::<X>(keys, q + 2, off), STRIDE);
        _tile_loadd::<7>(key::<X>(keys, q + 3, off), STRIDE);
        pair_sums::<2, 3>(r);
        q += 4;
    }
}

/// One pair's `1 + r` multiplies: data tile `A` by its matrix in tile 5 into chain 0, data `B` by tile 7 into chain 1.
#[inline(always)]
unsafe fn pair_sums<const A: i32, const B: i32>(r: usize) {
    _tile_dpbuud::<0, A, 5>();
    _tile_dpbuud::<1, B, 7>();
    for _ in 0..r {
        _tile_dpbuud::<0, A, 5>();
        _tile_dpbuud::<1, B, 7>();
    }
}

/// Whether the two chains' sums (`group_sums`) add up to `expected`, lane by lane, wrapping as the accumulator does.
#[inline(always)]
unsafe fn sums_match(sums: *const u32, expected: *const Tile) -> bool {
    // SAFETY: `group_sums` stored both chains, 256 lanes each, and a tile is 256 u32 lanes
    let (s0, s1, e) = unsafe {
        (
            &*sums.cast::<[u32; 2 * TILE_U64]>(),
            &*sums.add(2 * TILE_U64).cast::<[u32; 2 * TILE_U64]>(),
            &*expected.cast::<[u32; 2 * TILE_U64]>(),
        )
    };
    (0..2 * TILE_U64).fold(0, |acc, n| acc | (s0[n].wrapping_add(s1[n]) ^ e[n])) == 0
}

/// R for tiles outside a whole group (a chunk's partial groups at its ends): every word against its expected one, the differences ORed.
///
/// # Safety
/// `from..to` tiles of the extent at `base`.
#[inline(never)]
unsafe fn verify_part<const X: usize>(base: *const u64, from: usize, to: usize, set: &PatternSet<X>, pass: usize) -> u64 {
    let mut seen = 0;
    for t in from..to {
        let want = &set.expected_t[set.pattern_at(t, pass)].0;
        let tile = base.add(t * TILE_U64);
        for (w, &e) in want.iter().enumerate() {
            seen |= *tile.add(w) ^ e;
        }
    }
    seen
}

/// The checksum, at `r`, of a group holding `T(P_i)` at tile `i` (rotation 0): one of the set's expected values.
#[target_feature(enable = "amx-tile,amx-int8")]
unsafe fn group_checksum<const X: usize>(group: *const u64, keys: *const Matrix, r: usize) -> Tile {
    let _tiles = crate::amx::configure();
    let mut sums = [0u32; 4 * TILE_U64];
    group_sums::<X>(group, keys, 0, r, sums.as_mut_ptr());
    let total = |n: usize| sums[n].wrapping_add(sums[2 * TILE_U64 + n]);
    Tile(std::array::from_fn(|w| u64::from(total(2 * w)) | (u64::from(total(2 * w + 1)) << 32)))
}

/// Whether group `g`'s checksum, recomputed through the tiles, still disagrees: after a rescan, the other load path.
#[target_feature(enable = "amx-tile,amx-int8")]
unsafe fn checksum_still_wrong<const X: usize>(base: *const u64, g: usize, check: Check, pass: usize) -> bool {
    // SAFETY: the caller's
    unsafe { verify_groups::<X>(base, g, g + 1, check, pass) == g }
}

