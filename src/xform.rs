/// One differing word of a tile, by its index in the tile.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
struct BadWord {
    word: usize,
    expected: u64,
    actual: u64,
}

/// What a bad tile's differences look like.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum Signature {
    /// One bit of the stored result: byte `byte` of the tile (0..1024), bit `bit`.
    Stored { byte: usize, bit: u32 },
    /// One bit of the pattern, flipped before RW read it: byte `byte` of the pattern tile, bit `bit`, and whether it went from 0 to 1. One
    /// row of the result is off by `d * K[j][..]`, which names the byte (the transform's rows are distinct).
    BeforeTransform { byte: usize, bit: u32, rose: bool },
    /// Anything else: more than one bit, or neither shape.
    Other,
}

impl std::fmt::Display for Signature {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match *self {
            Signature::Stored { byte, bit } => write!(f, "one stored bit: byte {byte} bit {bit}"),
            Signature::BeforeTransform { byte, bit, rose } => {
                write!(f, "one bit flipped before the transform: pattern byte {byte} bit {bit}, {}", if rose { "0 to 1" } else { "1 to 0" })
            }
            Signature::Other => write!(f, "not one bit"),
        }
    }
}

/// The shape of `words` (one tile's differences, in word order) against the transform `k`.
fn signature(words: &[BadWord], k: &Matrix) -> Signature {
    if let [w] = words {
        let x = w.expected ^ w.actual;
        if x.count_ones() == 1 {
            let b = x.trailing_zeros() as usize;
            return Signature::Stored { byte: w.word * 8 + b / 8, bit: (b % 8) as u32 };
        }
    }
    // A flip in byte `j` of pattern row `m` moves all 16 entries of result row `m` (8 words) by `d * k[j][n]`, `d = +-2^b`; every entry of
    // `k` is odd, so all 16 move, by `2^b` times an odd byte
    let Some(first) = words.first() else { return Signature::Other };
    let row = first.word / 8;
    if words.len() != 8 || words.iter().any(|w| w.word / 8 != row) {
        return Signature::Other;
    }
    let delta: [i32; 16] = std::array::from_fn(|n| {
        let (w, shift) = (&words[n / 2], n % 2 * 32);
        ((w.actual >> shift) as u32).wrapping_sub((w.expected >> shift) as u32) as i32
    });
    let bit = delta[0].trailing_zeros();
    if bit > 7 {
        return Signature::Other;
    }
    let d = if delta[0] < 0 { -(1 << bit) } else { 1 << bit };
    let col = delta.map(|x| x / d);
    let odd_bytes = col.iter().all(|&c| (1..=255).contains(&c) && c % 2 == 1);
    if !odd_bytes || delta.iter().zip(&col).any(|(&x, &c)| x != c * d) {
        return Signature::Other;
    }
    match (0..64).find(|&j| (0..16).all(|n| i32::from(k.get(j, n)) == col[n])) {
        Some(j) => Signature::BeforeTransform { byte: row * ROW_BYTES + j, bit, rose: d > 0 },
        None => Signature::Other,
    }
}

/// Tier 2 on tiles `from..to` of the extent at `base`: every word against its expected one through `Rescan` (its bad-word lines, rereads,
/// failing bits and record; "not reproduced" when every word reads right), with a line per bad tile saying what its differences look like.
/// `what` names the check. Returns the errors to count.
#[cold]
#[inline(never)]
unsafe fn rescan_tiles<const X: usize>(base: *const u64, from: usize, to: usize, set: &PatternSet<X>, pass: usize, what: &str) -> u64 {
    let lead = crate::error_context::found_by(TEST_NAME);
    let (start, end) = (from * TILE_U64, to * TILE_U64);
    if !crate::pattern::rescan_enabled() {
        return unlocalised(lead, format_args!("in idx {start}..{end} ({what})"), 0);
    }
    let mut scan = Rescan::begin(base, lead.clone(), true);
    for t in from..to {
        let pattern = set.pattern_at(t, pass);
        let mut words = Vec::new();
        for (w, &expected) in set.expected_t[pattern].0.iter().enumerate() {
            // SAFETY: tile `t` is the caller's, inside the extent
            let actual = unsafe { scan.word_read(t * TILE_U64 + w, expected) };
            if actual != expected {
                words.push(BadWord { word: w, expected, actual });
            }
        }
        if !words.is_empty() {
            let signature = signature(&words, &set.m.transform);
            log::error!(
                "{lead}, tile {t} (idx {}..{}, pattern {pattern}): {} bad words, {signature}",
                t * TILE_U64,
                (t + 1) * TILE_U64,
                words.len()
            );
            #[cfg(test)]
            FOUND.with_borrow_mut(|f| f.push(BadTile { tile: t, pattern, bad_words: words.len(), signature }));
        }
    }
    scan.finish(format_args!("in idx {start}..{end} ({what})"))
}

/// Tier 2 for group `g`, whose checksum disagreed: its rescan, then the checksum again through the tiles (logged: with nothing reproduced,
/// "still wrong" means the tile path sees what word loads don't, a fault in the tile loads or the multiply). Returns the errors to count.
#[cold]
#[inline(never)]
unsafe fn rescan_group<const X: usize>(base: *const u64, g: usize, set: &PatternSet<X>, pass: usize) -> u64 {
    let what = format!("group {g}, pass {pass}: the group's checksum disagreed");
    // SAFETY: group `g` is the caller's, inside the extent
    let errors = unsafe { rescan_tiles::<X>(base, g * X, (g + 1) * X, set, pass, &what) };
    if crate::pattern::rescan_enabled() {
        // SAFETY: AMX-INT8, the test's (`amx::has_amx_int8` let it run); the R kernel's tile session has ended
        let still = unsafe { checksum_still_wrong::<X>(base, g, set.check(), pass) };
        log::error!(
            "{} in idx {}..{} (group {g}): the checksum through the tiles again: {}",
            crate::error_context::found_by(TEST_NAME),
            g * X * TILE_U64,
            (g + 1) * X * TILE_U64,
            if still { "still wrong" } else { "right" }
        );
        #[cfg(test)]
        RECHECKED.with(|r| r.set(Some(still)));
    }
    errors
}

